const loc = (sport, t) => (LOC[sport] || {})[ALIAS[t] || t] || (LOC[sport] || {})[t] || null;
function miles(sport, a, b) {   // great-circle distance between two teams' arenas
  const p = loc(sport, a), q = loc(sport, b); if (!p || !q) return null;
  const r = x => x * Math.PI / 180, h = Math.sin(r(q[0] - p[0]) / 2) ** 2 + Math.cos(r(p[0])) * Math.cos(r(q[0])) * Math.sin(r(q[1] - p[1]) / 2) ** 2;
  return 3959 * 2 * Math.asin(Math.sqrt(h));
}
function tzShift(sport, from, to) {   // hours moved east (positive) or west (negative) between two arenas
  const p = loc(sport, from), q = loc(sport, to); return p && q ? q[2] - p[2] : null;
}
